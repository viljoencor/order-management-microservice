// Steps
// Test creating orders with one and many products, including price and total maths.
// Test that missing products and duplicates are rejected before anything is saved.
// Test get by id, unknown id and listing.
package com.orderflow.order;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import com.orderflow.order.dto.CreateOrderRequest;
import com.orderflow.order.dto.OrderItemRequest;
import com.orderflow.product.Product;
import com.orderflow.product.ProductRepository;
import java.math.BigDecimal;
import java.util.List;
import java.util.Optional;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.http.HttpStatus;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.web.server.ResponseStatusException;

// Similar to a pytest test using unittest.mock for both repositories. No database or Spring context.
@ExtendWith(MockitoExtension.class)
class OrderServiceTest {

    @Mock
    private OrderRepository orderRepository;

    @Mock
    private ProductRepository productRepository;

    private OrderService service;

    @BeforeEach
    void setUp() {
        service = new OrderService(orderRepository, productRepository);
    }

    private Product product(long id, String name, String price) {
        Product product = new Product(name, new BigDecimal(price));
        // Ids are normally generated by the database, so tests set them directly.
        ReflectionTestUtils.setField(product, "id", id);
        return product;
    }

    private CreateOrderRequest request(OrderItemRequest... items) {
        return new CreateOrderRequest(List.of(items));
    }

    private void saveReturnsArgument() {
        when(orderRepository.save(any(Order.class))).thenAnswer(invocation -> invocation.getArgument(0));
    }

    @Test
    void createsOrderWithOneProduct() {
        when(productRepository.findAllById(List.of(1L))).thenReturn(List.of(product(1, "Keyboard", "450.00")));
        saveReturnsArgument();

        Order order = service.create(request(new OrderItemRequest(1L, 1)));

        assertThat(order.getItems()).hasSize(1);
        assertThat(order.getItems().get(0).getProduct().getName()).isEqualTo("Keyboard");
        assertThat(order.getTotalPrice()).isEqualByComparingTo("450.00");
    }

    @Test
    void createsOrderWithMultipleProductsAndCalculatesTotal() {
        when(productRepository.findAllById(List.of(1L, 2L))).thenReturn(List.of(
                product(1, "Keyboard", "450.50"),
                product(2, "Mouse", "19.99")));
        saveReturnsArgument();

        Order order = service.create(request(new OrderItemRequest(1L, 2), new OrderItemRequest(2L, 3)));

        assertThat(order.getItems()).hasSize(2);
        assertThat(order.getItems().get(0).getLineTotal()).isEqualByComparingTo("901.00");
        assertThat(order.getItems().get(1).getLineTotal()).isEqualByComparingTo("59.97");
        // 901.00 + 59.97, which would drift with double arithmetic in other cases.
        assertThat(order.getTotalPrice()).isEqualByComparingTo("960.97");
    }

    @Test
    void copiesCurrentProductPriceIntoItems() {
        when(productRepository.findAllById(List.of(1L))).thenReturn(List.of(product(1, "Keyboard", "450.50")));
        saveReturnsArgument();

        Order order = service.create(request(new OrderItemRequest(1L, 4)));

        assertThat(order.getItems().get(0).getUnitPrice()).isEqualByComparingTo("450.50");
        assertThat(order.getItems().get(0).getQuantity()).isEqualTo(4);
    }

    @Test
    void rejectsMissingProductAndSavesNothing() {
        when(productRepository.findAllById(List.of(1L, 7L))).thenReturn(List.of(product(1, "Keyboard", "450.00")));

        assertThatThrownBy(() -> service.create(request(new OrderItemRequest(1L, 1), new OrderItemRequest(7L, 1))))
                .isInstanceOfSatisfying(ResponseStatusException.class, e -> {
                    assertThat(e.getStatusCode()).isEqualTo(HttpStatus.NOT_FOUND);
                    assertThat(e.getBody().getProperties()).containsEntry("missingProductIds", List.of(7L));
                });

        verify(orderRepository, never()).save(any());
    }

    @Test
    void reportsAllMissingProductIds() {
        when(productRepository.findAllById(List.of(9L, 3L, 5L))).thenReturn(List.of(product(5, "Mouse", "10.00")));

        assertThatThrownBy(() -> service.create(request(
                new OrderItemRequest(9L, 1), new OrderItemRequest(3L, 1), new OrderItemRequest(5L, 1))))
                .isInstanceOfSatisfying(ResponseStatusException.class,
                        e -> assertThat(e.getBody().getProperties())
                                .containsEntry("missingProductIds", List.of(3L, 9L)));

        verify(orderRepository, never()).save(any());
    }

    @Test
    void rejectsDuplicateProductIds() {
        assertThatThrownBy(() -> service.create(request(new OrderItemRequest(1L, 1), new OrderItemRequest(1L, 2))))
                .isInstanceOfSatisfying(ResponseStatusException.class,
                        e -> assertThat(e.getStatusCode()).isEqualTo(HttpStatus.BAD_REQUEST));

        verify(orderRepository, never()).save(any());
    }

    @Test
    void rejectsTotalLargerThanTheDatabaseColumnCanHold() {
        when(productRepository.findAllById(List.of(1L))).thenReturn(
                List.of(product(1, "Gold bar", "99999999999999999.99")));

        assertThatThrownBy(() -> service.create(request(new OrderItemRequest(1L, 2))))
                .isInstanceOfSatisfying(ResponseStatusException.class,
                        e -> assertThat(e.getStatusCode()).isEqualTo(HttpStatus.BAD_REQUEST));

        verify(orderRepository, never()).save(any());
    }

    @Test
    void getByIdReturnsExistingOrder() {
        Order order = new Order(List.of(), BigDecimal.ZERO);
        when(orderRepository.findById(1L)).thenReturn(Optional.of(order));

        assertThat(service.getById(1L)).isSameAs(order);
    }

    @Test
    void getByIdThrowsNotFoundForUnknownOrder() {
        when(orderRepository.findById(99L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.getById(99L))
                .isInstanceOfSatisfying(ResponseStatusException.class,
                        e -> assertThat(e.getStatusCode()).isEqualTo(HttpStatus.NOT_FOUND));
    }

    @Test
    void listReturnsOrdersFromRepository() {
        List<Order> orders = List.of(new Order(List.of(), BigDecimal.ONE), new Order(List.of(), BigDecimal.TEN));
        when(orderRepository.findAllByOrderByIdAsc()).thenReturn(orders);

        assertThat(service.list()).containsExactlyElementsOf(orders);
    }

    @Test
    void listReturnsEmptyListWhenNoOrdersExist() {
        when(orderRepository.findAllByOrderByIdAsc()).thenReturn(List.of());

        assertThat(service.list()).isEmpty();
    }
}
